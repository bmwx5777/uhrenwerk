/**
 * Переключение светлой и тёмной темы.
 *
 * Выбор хранится в localStorage, а не в cookie, сознательно: cookie
 * пришлось бы читать в корневом layout, и тогда динамическими стали бы
 * все страницы сайта — включая главную и каталог, которые сейчас
 * отдаются статикой.
 *
 * Плата за это — необходимость поставить атрибут до первой отрисовки,
 * иначе страница моргнёт чужой темой. Этим занимается THEME_SCRIPT:
 * он выполняется синхронно в <head>, раньше, чем браузер что-то покажет.
 */

export const THEME_STORAGE_KEY = "uhrenwerk-theme";

export type Theme = "light" | "dark";

/** Тема по умолчанию, если пользователь ничего не выбирал. */
export const DEFAULT_THEME: Theme = "light";

/**
 * Код, встраиваемый в <head>. Намеренно без зависимостей и в одну
 * строку: он должен отработать до загрузки любого JS-бандла.
 *
 * Системная настройка `prefers-color-scheme` намеренно не учитывается:
 * светлая тема — основной облик магазина, и посетитель с тёмной темой
 * в системе должен увидеть именно его. Тёмная включается только явным
 * нажатием, и тогда выбор запоминается.
 *
 * Если localStorage недоступен (приватный режим, запрет на хранилище),
 * остаётся тема по умолчанию — поэтому весь код обёрнут в try/catch.
 */
export const THEME_SCRIPT = `(function(){try{var k=${JSON.stringify(THEME_STORAGE_KEY)};var s=localStorage.getItem(k);document.documentElement.setAttribute("data-theme",s==="dark"?"dark":"light");}catch(e){}})();`;
