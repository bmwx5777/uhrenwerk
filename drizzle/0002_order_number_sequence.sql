-- Последовательность для человекочитаемых номеров заказов: UW-2026-000123.
--
-- Почему последовательность, а не max(order_number) + 1: два одновременных
-- заказа прочитали бы одно и то же максимальное значение и получили бы
-- одинаковый номер. nextval атомарен и не блокирует другие транзакции.
--
-- Пропуски в нумерации допустимы (откат транзакции номер не возвращает) —
-- для номера заказа это нормально, в отличие от номера счёта, где
-- непрерывность требуется законом. Нумерацию счетов сделаем отдельно,
-- на этапе выставления документов.
CREATE SEQUENCE IF NOT EXISTS order_number_seq AS bigint START WITH 1 INCREMENT BY 1;
